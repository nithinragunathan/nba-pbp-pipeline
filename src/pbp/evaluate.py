"""Matcher evaluation on the real games.

Real NBA and ESPN data has no ground truth for which rows are the same event, so the matcher is
judged by the test that needs none: every made basket must be paired across sources, otherwise
the unified table counts its points twice. Three matchers are compared: the pipeline's matcher,
the same matcher with score-only anchors, and a plain clock-window baseline.

    python -m pbp.evaluate            # writes reports/matcher_evaluation.md
"""
from __future__ import annotations

from functools import partial

import duckdb
import pandas as pd

from pbp import config
from pbp.matching import _records, clock_window_match, match_pair

MAX_CLOCK_TENTHS = 120

MATCHERS = {
    "anchors + alignment (pipeline)": partial(match_pair, max_clock_tenths=MAX_CLOCK_TENTHS),
    "score-only anchors + alignment": partial(match_pair, max_clock_tenths=MAX_CLOCK_TENTHS, strict_anchors=False),
    "clock window ±2 s (baseline)": partial(clock_window_match, window_tenths=20),
}


def real_data_double_counting(events: pd.DataFrame) -> pd.DataFrame:
    """Made baskets left unpaired between NBA and ESPN on the real games (each one is counted twice
    in a unified table), per matcher."""
    rows = []
    games = {g: (_records(df[df["source"] == "nba"]), _records(df[df["source"] == "espn"]))
             for g, df in events.groupby("game_key")}
    for name, matcher in MATCHERS.items():
        unpaired, games_hit = 0, 0
        for xs, ys in games.values():
            paired_x = {i for i, *_ in matcher(xs, ys)}
            n = sum(1 for i, e in enumerate(xs)
                    if e["event_class"] in ("shot", "free_throw") and e["is_made"] and i not in paired_x)
            unpaired += n
            games_hit += n > 0
        rows.append({"matcher": name, "unpaired_made_baskets": unpaired, "games_affected": games_hit,
                     "games": len(games)})
    return pd.DataFrame(rows)


def _fmt(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def main() -> None:
    con = duckdb.connect(str(config.DB_PATH), read_only=True)
    # NBA only: the evaluation compares NBA Stats with ESPN.
    events = con.execute("select * from staging.stg_events where league = 'nba'").fetchdf()
    agreement = con.execute("""
        select event_class, sum(n_events_a) as nba_events, sum(n_events_b) as espn_events,
               sum(n_matched) as matched,
               round(sum(n_matched) / sum(n_events_a), 4) as nba_match_rate,
               round(sum(n_matched) / sum(n_events_b), 4) as espn_match_rate,
               round(avg(avg_abs_clock_diff_s), 3) as avg_abs_clock_diff_s,
               sum(n_player_disagree) as player_disagree, sum(n_result_disagree) as result_disagree
        from marts.rpt_source_agreement where game_key like 'nba_%'
        group by 1 order by event_class = 'all', 1""").fetchdf()
    con.close()
    num = agreement.columns.drop(["event_class", "nba_match_rate", "espn_match_rate", "avg_abs_clock_diff_s"])
    agreement[num] = agreement[num].astype(int)

    real = real_data_double_counting(events)

    md = "\n\n".join([
        "# Matcher evaluation",
        f"Generated by `python -m pbp.evaluate` from the {events.loc[events['source'] == 'nba', 'game_key'].nunique()} "
        f"NBA games with an official feed "
        f"({', '.join(sorted(events['season'].unique()))}) loaded in bronze.",
        "## 1. Real data: NBA vs ESPN agreement\n\n" + _fmt(agreement),
        "## 2. Real data: made baskets left unpaired (each would be double-counted)\n\n" + _fmt(real),
    ]) + "\n"
    path = config.REPORTS_DIR / "matcher_evaluation.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(md)
    print(md)


if __name__ == "__main__":
    main()
